"""Natural language -> spreadsheet formula."""

from __future__ import annotations

import re
from dataclasses import dataclass

from .llm import LLMClient, LLMMessage

_RANGE = r"([A-Z]{1,3}\d+(?::[A-Z]{1,3}\d+)?)"
_RULES: list[tuple[str, str, str]] = [
    (r"\b(sum|total|add up)\b", "SUM", "Sums the range"),
    (r"\b(average|mean|avg)\b", "AVERAGE", "Averages the range"),
    (r"\b(max|maximum|largest|highest)\b", "MAX", "Largest value in the range"),
    (r"\b(min|minimum|smallest|lowest)\b", "MIN", "Smallest value in the range"),
    (r"\b(count|how many)\b", "COUNT", "Counts numeric cells in the range"),
]


@dataclass
class Translation:
    formula: str
    explanation: str
    confidence: float
    source: str  # "rules" | "llm"


def translate(text: str, llm: LLMClient | None = None) -> Translation:
    upper = text.upper()
    rng = re.search(_RANGE, upper)
    if rng:
        for pattern, fn, explanation in _RULES:
            if re.search(pattern, text, re.IGNORECASE):
                return Translation(f"={fn}({rng.group(1)})", explanation, 0.9, "rules")
    if llm is None:
        return Translation("", "Could not translate; no LLM configured", 0.0, "rules")
    # TODO: constrain the LLM to the formula grammar and validate before returning.
    raw = llm.complete([
        LLMMessage("system", "Translate the instruction into one spreadsheet formula."),
        LLMMessage("user", text),
    ])
    return Translation(raw, "Generated by LLM (unverified)", 0.3, "llm")
